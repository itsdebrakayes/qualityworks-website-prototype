/** Generates docs/07-qa-testing-summary.md from qa-output/results.json (run after npm run qa:checks). */
import { readFileSync, writeFileSync } from 'node:fs';
const r = JSON.parse(readFileSync(new URL('../qa-output/results.json', import.meta.url)));
const esc = (s = '') => String(s).replace(/&/g, '&amp;').replace(/</g, '&lt;').replace(/>/g, '&gt;').replace(/\|/g, '/').replace(/\n/g, ' ').replace(/→/g, '›').replace(/≈/g, 'approx. ');
// QM-112 v0.5 requirement / acceptance-criteria IDs exercised by each automated test.
const QM112 = {
  'QA-01': '9.1, 9.2 / AC-SEO-01, AC-GLO-03', 'QA-02': '1.4 / AC-INV-02', 'QA-02B': '1.4 / AC-INV-02, AC-GLO-05', 'QA-03': '3.4, 7.3 / AC-SRV-03, AC-PRD-03',
  'QA-04': '4.12 / AC-GLO-03', 'QA-05': '9.1 / AC-SEO-01', 'QA-06': '9.2 / AC-SEO-01, AC-SEO-02', 'QA-07': '4.2 / AC-GLO-04',
  'QA-08': '4.1 / AC-GLO-03', 'QA-09': 'AC-GLO-01', 'QA-10': '1.3 / AC-GLO-02', 'QA-11': '1.3 / AC-GLO-02', 'QA-12': '1.3 / AC-GLO-02, AC-GLO-03',
  'QA-13': '1.3 / AC-GLO-02', 'QA-14': '1.3 / AC-GLO-02', 'QA-15': '1.3 / AC-GLO-02', 'QA-16': '2.1 / AC-HOM-01, AC-HOM-02', 'QA-17': '2.1, 2.3 / AC-HOM-02',
  'QA-18': '6.2 / AC-FRM-02', 'QA-19': '6.2 / AC-FRM-01, AC-FRM-02', 'QA-20': '6.3 / AC-FRM-02', 'QA-21': '6.2 / AC-FRM-02', 'QA-22': '6.2 / AC-FRM-02 (mocked)',
  'QA-23': '4.3, 4.5 / AC-IND-03', 'QA-24': '4.5 / AC-INV-04 (simulated)', 'QA-25': '5.4 / AC-RES-01', 'QA-26': '5.5 / AC-RES-04', 'QA-27': '7.2–7.4 / AC-CAR-02 (fixture states)',
  'QA-28': '2.2 / AC-SRV-02', 'QA-29': '4.1 / AC-GLO-04', 'QA-30': 'AC-OPS-04', 'QA-31': '6.4 / AC-FRM-02', 'QA-32': '4.1 / AC-GLO-03',
};
const qmRef = (id) => QM112[id] ?? QM112[id.replace(/-\d+$/, '')] ?? '—';
const count = (s) => r.results.filter((x) => x.status === s).length;
const externals = r.externalLinks.filter((u) => !u.includes('linkedin.com/sharing') && !u.includes('twitter.com/intent') && !u.startsWith('mailto')).slice(0, 60).map((u) => '- `' + u + '`').join('\n');
const manual = readFileSync(new URL('../docs/_manual-qa.md', import.meta.url), 'utf8');
const md = `---
title: "07 · QA testing summary"
summary: "Automated and manual verification results, with evidence and open issues."
---

# QA testing summary

**Run:** ${r.runAt.slice(0, 16).replace('T', ' ')} UTC against \`${r.base}\` · **Routes:** ${r.routes} · **Result:** ${count('Pass')} pass, ${count('Fail')} fail, ${count('Blocked')} blocked. Generated by \`scripts/qa-checks.mjs\` + \`scripts/qa-report.mjs\`; evidence screenshots in \`qa-output/evidence/\`.

**Rule applied:** a test is *Pass* only when the behaviour is actually exercised in the browser. Mocked behaviour (simulated submission, simulated loading/error, fixture vacancies) is stated in *Open issue*. Real integrations are **Blocked**, not passed. The QM-112 AC ID column cites QM-112 v0.5 requirement numbers and AC IDs (document read 18 Nov 2026).

| Test ID | QM-112 AC ID | Page/component | Expected behavior | Actual result | Pass/Fail/Blocked | Screenshot/evidence | Open issue |
|---|---|---|---|---|---|---|---|
${r.results.map((x) => `| ${x.id} | ${qmRef(x.id)} | ${esc(x.area)} | ${esc(x.expected)} | ${esc(x.actual).slice(0, 400)} | **${x.status}** | ${esc(x.evidence) || '—'} | ${esc(x.issue) || '—'} |`).join('\n')}

${manual}

## External destinations exercised by links (${r.externalLinks.length})
${externals}
`;
writeFileSync(new URL('../docs/07-qa-testing-summary.md', import.meta.url), md);
console.log('wrote docs/07-qa-testing-summary.md');
