/** Generates docs/07-qa-testing-summary.md from qa-output/results.json (run after npm run qa:checks). */
import { readFileSync, writeFileSync } from 'node:fs';
const r = JSON.parse(readFileSync(new URL('../qa-output/results.json', import.meta.url)));
const esc = (s = '') => String(s).replace(/\|/g, '/').replace(/\n/g, ' ').replace(/→/g, '›').replace(/≈/g, 'approx. ');
const count = (s) => r.results.filter((x) => x.status === s).length;
const externals = r.externalLinks.filter((u) => !u.includes('linkedin.com/sharing') && !u.includes('twitter.com/intent') && !u.startsWith('mailto')).slice(0, 60).map((u) => '- `' + u + '`').join('\n');
const manual = readFileSync(new URL('../docs/_manual-qa.md', import.meta.url), 'utf8');
const md = `---
title: "07 · QA testing summary"
summary: "Automated and manual verification results, with evidence and open issues."
---

# QA testing summary

**Run:** ${r.runAt.slice(0, 16).replace('T', ' ')} UTC against \`${r.base}\` · **Routes:** ${r.routes} · **Result:** ${count('Pass')} pass, ${count('Fail')} fail, ${count('Blocked')} blocked. Generated by \`scripts/qa-checks.mjs\` + \`scripts/qa-report.mjs\`; evidence screenshots in \`qa-output/evidence/\`.

**Rule applied:** a test is *Pass* only when the behaviour is actually exercised in the browser. Mocked behaviour (simulated submission, simulated loading/error, fixture vacancies) is stated in *Open issue*. Real integrations are **Blocked**, not passed. QM-112 AC IDs could not be retrieved (source inaccessible), so the column shows the QM-113 brief requirement instead.

| Test ID | QM-112 AC ID | Page/component | Expected behavior | Actual result | Pass/Fail/Blocked | Screenshot/evidence | Open issue |
|---|---|---|---|---|---|---|---|
${r.results.map((x) => `| ${x.id} | ${esc(x.ac)} (QM-112 ID n/a) | ${esc(x.area)} | ${esc(x.expected)} | ${esc(x.actual).slice(0, 400)} | **${x.status}** | ${esc(x.evidence) || '—'} | ${esc(x.issue) || '—'} |`).join('\n')}

${manual}

## External destinations exercised by links (${r.externalLinks.length})
${externals}
`;
writeFileSync(new URL('../docs/07-qa-testing-summary.md', import.meta.url), md);
console.log('wrote docs/07-qa-testing-summary.md');
