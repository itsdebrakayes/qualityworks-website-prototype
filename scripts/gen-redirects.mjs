/**
 * gen-redirects.mjs — writes `<outDir>/_redirects` (Netlify / Cloudflare Pages format) for the
 * case-study URL changes made in review rounds 1–2.
 *
 * WHY: case studies moved from WordPress `/case-study/{slug}/` to `/case-studies/{slug}/` (round 1),
 * and one slug was renamed to remove a client product name (round 2). Search engines and old links
 * need permanent (301) redirects.
 *
 * STATUS: PENDING. The file is generated so a future host can use it, but NO host is configured and
 * the prototype viewer (Claude Artifact) cannot execute redirects. Do not report redirects as working
 * until they are tested on the chosen host (QM-112 9.5 / 11.5).
 *
 * Usage: node scripts/gen-redirects.mjs [outDir]   (default: dist)
 */
import { readFileSync, writeFileSync, existsSync } from 'node:fs';

const outDir = process.argv[2] ?? 'dist';
const read = (p) => JSON.parse(readFileSync(new URL(p, import.meta.url), 'utf8'));
// Every WordPress case study, keyed by its original slug.
const caseStudies = read('../src/data/migrated/case-studies.wp-snapshot.json');
// Neutral renames (legacy slug -> public slug). Single source of truth for legacy slugs.
const { caseStudySlugRenames: renames } = read('../src/data/redirects.json');

const lines = ['# Generated by scripts/gen-redirects.mjs — PENDING: not configured on any host.'];
for (const { slug } of caseStudies) {
  const target = `/case-studies/${renames[slug] ?? slug}/`;
  // 1) Legacy WordPress detail URL -> new detail URL (one hop, no chains).
  lines.push(`/case-study/${slug}/  ${target}  301`);
  // 2) If the slug was renamed, the round-1 prototype URL also redirects straight to the target.
  if (renames[slug]) lines.push(`/case-studies/${slug}/  ${target}  301`);
}
if (!existsSync(outDir)) throw new Error(`Output directory ${outDir} does not exist — run the build first`);
writeFileSync(`${outDir}/_redirects`, lines.join('\n') + '\n');
console.log(`gen-redirects: wrote ${lines.length - 1} redirect rules to ${outDir}/_redirects (pending host configuration)`);
